import express, { Router } from 'express';
import { z } from 'zod';
import { BoneSchema, CubeSchema, encodeRgbaPng, LIMITS, SkinModelSchema, bytesToBase64 } from '@blockwright/shared';
import { createBlankSkin, createTemplateSkin, TEMPLATE_PRESETS, validateSkinPng } from '@blockwright/minecraft-skin';
import type { AppDeps } from '../app.js';
import { AppError } from '../http/errors.js';
import { sendData } from '../http/envelope.js';

const jsonLarge = express.json({ limit: Math.ceil(LIMITS.maxProjectJsonBytes * 1.5) });

const CreateSkinBody = z.object({
  state: z.record(z.string(), z.unknown()),
  skinPngBase64: z.string().max(400_000).optional(),
  template: z
    .object({ kind: z.enum(['template', 'blank']), preset: z.string().max(32).optional() })
    .optional(),
});
const UpdateBody = z.object({
  baseRevision: z.number().int().positive(),
  state: z.record(z.string(), z.unknown()),
  skinPngBase64: z.string().max(400_000).optional(),
  label: z.string().max(60).optional(),
});
const RevertBody = z.object({ baseRevision: z.number().int().positive(), toRevision: z.number().int().positive() });
const ApplyBody = z.object({ baseRevision: z.number().int().positive(), artifactId: z.string() });

export function projectRoutes(deps: AppDeps): Router {
  const r = Router();

  r.post('/skin', jsonLarge, async (req, res) => {
    const body = CreateSkinBody.parse(req.body);
    let png = body.skinPngBase64;
    if (!png) {
      const model = SkinModelSchema.parse(body.state.model);
      const preset = TEMPLATE_PRESETS[body.template?.preset ?? 'explorer'] ?? TEMPLATE_PRESETS.explorer!;
      const img = body.template?.kind === 'blank' ? createBlankSkin(model) : createTemplateSkin(model, preset);
      png = bytesToBase64(encodeRgbaPng(img));
    }
    sendData(req, res, await deps.projects.createSkin(req.session!.ownerId, body.state, png), 201);
  });

  r.post('/entity', jsonLarge, async (req, res) => {
    const body = z.object({ state: z.record(z.string(), z.unknown()) }).parse(req.body);
    sendData(req, res, await deps.projects.createEntity(req.session!.ownerId, body.state), 201);
  });

  r.get('/:id', async (req, res) => {
    sendData(req, res, await deps.projects.get(req.session!.ownerId, req.params.id));
  });

  r.put('/:id', jsonLarge, async (req, res) => {
    const body = UpdateBody.parse(req.body);
    sendData(req, res, await deps.projects.update(req.session!.ownerId, req.params.id, body.baseRevision, body.state, body.skinPngBase64, body.label));
  });

  r.delete('/:id', async (req, res) => {
    await deps.projects.delete(req.session!.ownerId, req.params.id);
    sendData(req, res, { deleted: true });
  });

  r.get('/:id/revisions', async (req, res) => {
    sendData(req, res, { revisions: await deps.projects.history(req.session!.ownerId, req.params.id) });
  });

  r.post('/:id/revert', express.json({ limit: '4kb' }), async (req, res) => {
    const body = RevertBody.parse(req.body);
    sendData(req, res, await deps.projects.revert(req.session!.ownerId, req.params.id, body.baseRevision, body.toRevision));
  });

  /**
   * Apply a completed generation result as a new revision. Provenance (AI vs
   * imported mesh) is taken from the server's artifact record, never from the client.
   */
  r.post('/:id/apply', express.json({ limit: '4kb' }), async (req, res) => {
    const ownerId = req.session!.ownerId;
    const body = ApplyBody.parse(req.body);
    const { record, bytes } = await deps.exports.getArtifact(ownerId, body.artifactId);
    if (!record.jobId) throw new AppError(400, 'BAD_REQUEST', 'Only generation results can be applied to a project.');
    if (record.kind === 'skin-png') {
      const project = await deps.projects.get(ownerId, req.params.id);
      if (project.project.type !== 'skin') throw new AppError(400, 'BAD_REQUEST', 'This result is a skin; open a skin project.');
      const { image } = validateSkinPng(bytes, project.project.model);
      if (!image) throw new AppError(422, 'EXPORT_INVALID', 'The generated skin is not a valid PNG.');
      const view = await deps.projects.applyGenerated(
        ownerId,
        req.params.id,
        body.baseRevision,
        {
          provenance: {
            origin: 'ai',
            providerId: record.providerId ?? 'unknown',
            jobId: record.jobId,
            editedAfterGeneration: false,
            inferredRegions: [],
            notes: ['Generated by Sking SKING_DDJ_v101c from a reviewed two-view composite.'],
          },
          skinPng: encodeRgbaPng(image),
        },
        'Applied AI skin',
      );
      sendData(req, res, view);
      return;
    }
    if (record.kind === 'cuboid-model') {
      const model = z.object({ bones: z.array(BoneSchema), cubes: z.array(CubeSchema) }).parse(JSON.parse(bytes.toString('utf8')));
      const ai = record.origin === 'ai';
      const view = await deps.projects.applyGenerated(
        ownerId,
        req.params.id,
        body.baseRevision,
        {
          provenance: {
            origin: ai ? 'ai' : 'import',
            providerId: record.providerId ?? 'mesh-cuboids-v1',
            jobId: record.jobId,
            editedAfterGeneration: false,
            inferredRegions: [],
            notes: [ai ? 'TripoSR single-image mesh converted to cuboids; hidden sides are guessed by the model.' : 'Imported mesh converted to cuboids.'],
          },
          model,
          ...(record.sourceMeshArtifactId ? { sourceMeshArtifactId: record.sourceMeshArtifactId } : {}),
        },
        ai ? 'Applied AI mesh conversion' : 'Applied mesh conversion',
      );
      sendData(req, res, view);
      return;
    }
    throw new AppError(400, 'BAD_REQUEST', 'This result cannot be applied to a project.');
  });

  return r;
}
